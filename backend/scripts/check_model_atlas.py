def balanced(text: str, open_index: int) -> str:
    depth = 0
    for i in range(open_index, len(text)):
        if text[i] == '(':
            depth += 1
        elif text[i] == ')':
            depth -= 1
            if depth == 0:
                return text[open_index + 1:i]
    raise ValueError('unbalanced parentheses')


def split_top(body: str) -> list[str]:
    parts, depth, current = [], 0, ''
    for ch in body:
        depth += ch == '('
        depth -= ch == ')'
        if ch == ',' and depth == 0:
            parts.append(current)
            current = ''
        else:
            current += ch
    return parts + [current]


def parse_tables(text: str) -> dict[str, dict[str, dict]]:
    tables = {}
    for m in re.finditer(r'CREATE TABLE (\w+)\(', text):
        columns = {}
        for part in split_top(balanced(text, m.end() - 1)):
            tokens = part.split()
            if not tokens or re.match(r'(UNIQUE|PRIMARY|CHECK|FOREIGN|CONSTRAINT)\b', tokens[0], re.I):
                continue
            upper = part.upper()
            pk = 'PRIMARY KEY' in upper
            columns[tokens[0]] = {'type': tokens[1].upper(), 'nullable': not (pk or 'NOT NULL' in upper), 'pk': pk}
        tables[m.group(1)] = columns
    return tables


def view_texts(sql: str) -> dict[str, str]:
    starts = [(m.start(), m.group(1)) for m in re.finditer(r'CREATE VIEW (\w+) AS', sql)]
    out = {}
    for start, name in starts:
        rest = sql[start:]
        nxt = re.search(r'\nCREATE ', rest[1:])
        out[name] = rest if nxt is None else rest[:nxt.start() + 1]
    return out


def module_names(tree: ast.Module) -> set[str]:
    names = set()
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef, ast.AsyncFunctionDef)):
            names.add(node.name)
        elif isinstance(node, ast.Assign):
            names.update(t.id for t in node.targets if isinstance(t, ast.Name))
    return names


def constant(tree: ast.Module, name: str):
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == name for t in node.targets):
            return ast.literal_eval(node.value)
    raise KeyError(name)


def code_contract(root: Path) -> dict:
    pkg = Package(root)
    sql = (root / 'cuneiform/schema.sql').read_text()
    model = pkg.modules['cuneiform/model.py']
    proj = pkg.modules['cuneiform/projections.py']
    node_kinds = {}
    for node in model.body:
        if isinstance(node, ast.ClassDef) and node.name == 'NodeKind':
            for item in node.body:
                if isinstance(item, ast.Assign):
                    node_kinds[item.targets[0].id] = ast.literal_eval(item.value)
    tables = parse_tables(sql)
    for n in ast.walk(proj):
        if isinstance(n, ast.Constant) and isinstance(n.value, str) and n.value.startswith('CREATE TABLE'):
            tables.update(parse_tables(n.value))
    views = view_texts(sql)
    node_tables = {kind: table for kind, table in
                   re.findall(r"SELECT id,'(\w+)'(?: AS kind)? FROM (\w+)", views.get('nodes', ''))}
    portable = {}
    for part in views.get('portable_edge', '').split('UNION ALL')[1:]:
        kind = re.search(r"'([A-Z_]{3,})'", part)
        table = re.search(r'FROM (\w+)', part)
        if kind and table:
            portable.setdefault(kind.group(1), set()).add(table.group(1))
    written_tables, written_edges = set(re.findall(r'INSERT INTO (\w+)', sql)), {}
    symbols = {}
    for rel, tree in pkg.modules.items():
        symbols[rel] = module_names(tree)
        for n in ast.walk(tree):
            if isinstance(n, ast.Constant) and isinstance(n.value, str):
                written_tables.update(re.findall(r'INSERT INTO (\w+)', n.value))
            if isinstance(n, ast.Call) and n.args and const_str(n.args[0]) is not None:
                attr = n.func.attr if isinstance(n.func, ast.Attribute) else n.func.id if isinstance(n.func, ast.Name) else None
                # Builder.add('<table>', ...), Spool.detached('<table>', ...), Spool('<table>', ...)
                if attr in ('add', 'detached', 'Spool'):
                    written_tables.add(n.args[0].value)
                elif attr == 'edge':
                    written_edges.setdefault(n.args[0].value, set()).update(k.arg for k in n.keywords if k.arg)
    edge_registry, edge_problems = registry(pkg, 'cuneiform/model.py', 'EDGE_TYPES')
    edge_types = {}
    for k, v in edge_registry.items():
        try:
            edge_types[k] = tuple(ast.literal_eval(v))
        except ValueError:
            edge_problems.append(Unsupported('cuneiform/model.py', v, f'EDGE_TYPES[{k!r}] is not a literal endpoint pair'))
    rights, rights_problems = registry(pkg, 'cuneiform/adapters.py', 'RIGHTS')
    manifests, manifest_problems = snapshot_manifests(pkg)
    required, required_problems = verify_required(pkg)
    kinds, kind_problems = source_kinds(pkg)
    for m in manifests:
        r = m['keys'].get('rights')
        m['rights'] = rights_origin(pkg, r[0], r[1]) if r else ('missing', None)
        m['rights_statement'] = rights_statement(pkg, r[0], r[1]) if r else None
        # For RIGHTS[source] lookups: is the index the same name as the manifest's 'source' value?
        src, idx = m['keys'].get('source'), registry_index(r[0]) if r else None
        m['rights_indexed_by_source'] = bool(src and idx is not None and isinstance(idx, ast.Name) and isinstance(src[0], ast.Name)
                                             and idx.id == src[0].id and src[1][1] is r[1][1])
    rights_literals = {}
    for k, v in rights.items():  # status of each registry namespace, where the code states it literally
        node = v
        if isinstance(node, ast.Subscript) and const_str(node.slice) in rights:
            node = rights[node.slice.value]
        try:
            rights_literals[k] = ast.literal_eval(node).get('status')
        except (ValueError, AttributeError, TypeError, SyntaxError):
            rights_literals[k] = None
    registry_row = re.search(r"INSERT INTO registry VALUES \('([^']*)',\s*'([^']*)'\)", sql)
    return {
        'versions': {'schema': constant(model, 'SCHEMA_VERSION'), 'parser': constant(model, 'PARSER_VERSION'),
                     'projection': constant(proj, 'REVISION')},
        'registry_row': registry_row.groups() if registry_row else None,
        'node_kinds': set(node_kinds.values()), 'node_tables': node_tables,
        'edge_types': edge_types, 'edge_problems': edge_problems, 'portable': portable,
        'tables': tables, 'views': set(views), 'written_tables': written_tables, 'written_edges': written_edges,
        'symbols': symbols, 'manifests': manifests, 'manifest_problems': manifest_problems + required_problems,
        'verify_required': required, 'rights_keys': set(rights), 'rights_problems': rights_problems,
        'rights_status_code': rights_literals,
        'source_kinds': kinds, 'source_problems': kind_problems,
    }


def file_sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def fingerprint(root: Path) -> dict[str, str]:
    out = {}
    for pattern in FINGERPRINT_GLOBS:
        for p in sorted(root.glob(pattern)):
            if p.is_file() and '__pycache__' not in p.parts:
                out[str(p.relative_to(root))] = file_sha(p)
    return out


def at_baseline(atlas: dict, r: dict) -> bool:
    """Render-time test: the run was recorded at the baseline commit (both >= 7 hex, one a prefix of the other).
    check() additionally resolves both with git and compares the code trees (R5)."""
    a, b = str(r.get('code_ref', '')), str(atlas.get('baseline_commit', ''))
    return bool(HEX_REF.fullmatch(a) and HEX_REF.fullmatch(b)) and (a.startswith(b) or b.startswith(a))


def support(atlas: dict, e: dict) -> list[dict]:
    """Passing runs at the baseline commit that back this entry's verified level."""
    level = e['status']['verified']
    if level not in ('unit', 'disk'):
        return []
    runs = {r.get('id'): r for r in atlas.get('verification_runs', [])}
    pool = [runs[r] for r in (e.get('verified_by') or runs) if r in runs]
    return [r for r in pool if r.get('outcome') == 'pass' and LEVEL_RANK.get(r.get('level'), 0) >= LEVEL_RANK[level]
            and at_baseline(atlas, r)]


def verified_label(atlas: dict, e: dict) -> str:
    """'disk (UNVERIFIED)' unless a backing run at the baseline was read back by the parent or the observer."""
    level = e['status']['verified']
    if level in ('unit', 'disk') and not any(r.get('read_back') for r in support(atlas, e)):
        return f'{level} (UNVERIFIED)'
    return level


# ---------------------------------------------------------------- queue

def parse_queue(root: Path) -> dict:
    text = (root / QUEUE).read_text()
    blocks = {}
    heads = list(re.finditer(r'^## (Q-\d{3})\b.*$', text, re.M))
    for i, h in enumerate(heads):
        body = text[h.end():heads[i + 1].start() if i + 1 < len(heads) else len(text)]
        status = re.search(r'^- \*\*Status:\*\*\s*`?([A-Z_]+)', body, re.M)
        depends = re.search(r'^- \*\*Depends on:\*\*(.*)$', body, re.M)
        blocks.setdefault(h.group(1), []).append({
            'status': status.group(1) if status else None,
            'depends': re.findall(r'Q-\d{3}', depends.group(1)) if depends else None,
            'body': body,
        })
    rows = {m.group(1): m.group(2) for m in
            re.finditer(r'^\|\s*\[?(Q-\d{3})\]?[^|]*\|[^|]*\|\s*`?([A-Z_]+)', text, re.M)}
    return {'text': text, 'blocks': blocks, 'rows': rows}


# ---------------------------------------------------------------- checks

def ref_path(root: Path, ref: str) -> Path:
    return root / re.split(r'[#\s]| §', ref, maxsplit=1)[0]


def endpoints(value) -> list[str]:
    return value if isinstance(value, list) else [value]


def gate(e: dict, check_name: str, problems: list[Unsupported], root: Path, errors: list, warnings: list) -> bool:
    """True when static analysis was complete. Otherwise fail, unless a fingerprinted contract is declared."""
    eid = e.get('id', '?')
    contract = (e.get('implementation', {}).get('static_contracts') or {}).get(check_name)
    if not problems:
        if contract:
            warnings.append(f'{eid}: static_contracts.{check_name} is no longer needed (analysis is complete); remove it')
        return True
    if not contract:
        for p in problems:
            errors.append(f'{eid}: unsupported static analysis ({check_name}), so the inventory cannot be proven complete: '
                          f'{p}. Rewrite into a supported form or declare implementation.static_contracts.{check_name}.')
        return False
    ok = True
    test = contract.get('evidence', '')
    path, _, fn = test.partition('::')
    if not test.startswith('tests/') or not (root / path).exists() or (fn and not re.search(rf'def {re.escape(fn)}\b', (root / path).read_text())):
        errors.append(f'{eid}: static_contracts.{check_name} needs an existing tests/ evidence reference')
        ok = False
    prints = contract.get('fingerprints') or {}
    for p in problems:
        if p.file not in prints:
            errors.append(f'{eid}: static_contracts.{check_name} does not fingerprint {p.file}, where analysis failed: {p}')
            ok = False
    for f, sha in prints.items():
        if not (root / f).exists() or file_sha(root / f) != sha:
            errors.append(f'{eid}: static_contracts.{check_name} is stale: {f} changed since the contract was verified')
            ok = False
    if ok:
        warnings.append(f'{eid}: {check_name} accepted from declared contract ({contract.get("reason", "no reason")}); '
                        f'{len(problems)} unsupported form(s)')
    return False


def check(root: Path, runtime: bool = False, samples: Path | None = EVIDENCE_DIR, real_root: Path | None = None,
          data_root: Path = DATA_ROOT, worktree: bool = False, repo: Path | None = None,
          head: str = 'HEAD') -> tuple[list[str], list[str]]:
    errors, warnings = [], []
    err = errors.append
    real_root = real_root or root
    git = Git(repo or real_root)
    if git.repo is None:
        err(f'git: no repository at {repo or real_root} (pass --repo); baseline, verification-run and DONE commits '
            'cannot be resolved, so commit-bound evidence is refused')
    try:
        atlas = json.loads((root / ATLAS).read_text())
    except (OSError, ValueError) as exc:
        return [f'{ATLAS}: unreadable ({exc})'], []
    code = code_contract(root)
    queue = parse_queue(root)
    entries = atlas.get('entries', [])
    by_id = {}
    for e in entries:
        if e.get('id') in by_id:
            err(f"duplicate entry id {e.get('id')}")
        by_id[e.get('id')] = e
    domains = {d['id'] for d in atlas.get('domains', [])}

    # -- versions
    if atlas.get('versions') != code['versions']:
        err(f"versions {atlas.get('versions')} != code {code['versions']}")
    if code['registry_row'] != (code['versions']['schema'], code['versions']['parser']):
        err(f"schema.sql registry row {code['registry_row']} disagrees with model.py versions")

    # -- verification runs (who observed what, at which commit)
    runs = {}
    for r in atlas.get('verification_runs', []):
        rid = r.get('id', '?')
        if rid in runs:
            err(f'verification run {rid}: duplicate id')
        runs[rid] = r
        for key in ('observer', 'date', 'command', 'result', 'code_ref', 'level', 'outcome', 'attribution'):
            if not r.get(key):
                err(f'verification run {rid}: missing {key}')
        if not isinstance(r.get('read_back'), bool):
            err(f'verification run {rid}: read_back must be true (observed by this atlas worker or the parent) '
                'or false (claimant-reported, rendered UNVERIFIED)')
        if r.get('level') not in ('unit', 'disk'):
            err(f"verification run {rid}: level {r.get('level')!r} not in ('unit', 'disk')")
        if r.get('outcome') not in ('pass', 'fail'):
            err(f"verification run {rid}: outcome {r.get('outcome')!r} not in ('pass', 'fail')")
    baseline = str(atlas.get('baseline_commit', ''))
    checked_code = code_blobs(root)
    base_sha = git.commit(baseline)
    baseline_stale = None
    if git.repo is not None:
        if not base_sha:
            err(f'baseline_commit {baseline!r} does not resolve to a commit in {git.repo} (need 7-40 hex naming a commit, '
                'not a task ID, tree or unknown object)')
        else:
            changed = tree_diff(git.code_tree(base_sha), checked_code)
            if changed:
                baseline_stale = changed
    for rid, r in runs.items():
        if git.repo is not None and not git.commit(r.get('code_ref')):
            err(f"verification run {rid}: code_ref {r.get('code_ref')!r} does not resolve to a commit (7-40 hex)")

    def current(r):
        """The run's commit has exactly the checked code under CODE_PATHS (doc-only commits do not matter)."""
        sha = git.commit(r.get('code_ref'))
        return bool(sha) and not tree_diff(git.code_tree(sha), checked_code)
    stale_entries = []

    # -- corpus snapshot eligibility (R1): which real snapshots may be cited as corpus evidence, and why
    snapshots = atlas.get('corpus_snapshots') or {}
    for sid, s in sorted(snapshots.items()):
        if not SNAPSHOT_ID.fullmatch(sid) or not isinstance(s, dict):
            err(f'corpus_snapshots: {sid} must be snapshot:<32 hex> with an object value')
            continue
        if s.get('status') not in ('accepted', 'pending-review', 'incident'):
            err(f"corpus_snapshots.{sid}: status {s.get('status')!r} not in ('accepted', 'pending-review', 'incident')")
        if not re.fullmatch(r'[0-9a-f]{64}', str(s.get('manifest_sha256', ''))):
            err(f'corpus_snapshots.{sid}: needs the observed manifest_sha256 (64 hex)')
        if s.get('status') == 'accepted':
            refs = s.get('accepted_by') or []
            if not refs:
                err(f'corpus_snapshots.{sid}: accepted needs accepted_by naming a reviews/ file that read it')
            for ref in refs:
                path = root / ref
                if not ref.startswith('reviews/') or not path.is_file():
                    err(f'corpus_snapshots.{sid}: accepted_by {ref} is not an existing reviews/ file')
                elif sid[9:17] not in path.read_text():
                    err(f'corpus_snapshots.{sid}: accepted_by {ref} never mentions {sid[9:17]}')
            if not s.get('note'):
                err(f'corpus_snapshots.{sid}: accepted needs a note on what the review established')
    for e in entries:
        for item in e.get('corpus_evidence') or []:
            sid = str(item.get('snapshot_id'))
            st = (snapshots.get(sid) or {}).get('status', 'unlisted')
            if st != 'accepted':
                err(f"{e.get('id')}: corpus evidence cites {sid}, whose corpus_snapshots status is {st}; incident, rebuilt "
                    'and unreviewed snapshots are never independent evidence')

    # -- per-entry structure and status rules
    for e in entries:
        eid = e.get('id', '?')
        for key in ('id', 'kind', 'domain', 'label', 'summary', 'status', 'implementation', 'queue'):
            if key not in e:
                err(f'{eid}: missing {key}')
        if e.get('domain') not in domains:
            err(f"{eid}: unknown domain {e.get('domain')}")
        if e.get('kind') in PREFIX and not eid.startswith(PREFIX[e['kind']]):
            err(f"{eid}: kind {e['kind']} requires prefix {PREFIX[e['kind']]}")
        st = e.get('status', {})
        for dim, allowed in STATUS.items():
            if st.get(dim) not in allowed:
                err(f'{eid}: status.{dim}={st.get(dim)!r} not in {allowed}')
        if st.get('populated') != 'none' and st.get('implemented') != 'code':
            err(f'{eid}: populated={st.get("populated")} requires implemented=code')
        if st.get('modeled') == 'proposed' and st.get('implemented') != 'none':
            err(f'{eid}: proposed entries must have implemented=none')
        tests = [r for r in e.get('evidence', []) if r.startswith('tests/')]
        level = st.get('verified')
        if level != 'none':
            if st.get('implemented') == 'none':
                err(f'{eid}: verified requires an implementation')
            if not tests:
                err(f'{eid}: verified={level} needs a tests/ evidence reference')
        if level in ('unit', 'disk'):
            named = e.get('verified_by')
            if level == 'disk' and not named:
                err(f'{eid}: verified=disk must name its run in verified_by so the observer is visible')
            for rid in named or []:
                if rid not in runs:
                    err(f'{eid}: verified_by names unknown run {rid}')
            pool = [runs[r] for r in (named or runs) if r in runs]
            support = [r for r in pool if r.get('outcome') == 'pass' and LEVEL_RANK.get(r.get('level'), 0) >= LEVEL_RANK[level]]
            if not support:
                err(f'{eid}: verified={level} has no passing {level}-level verification run')
            elif not any(current(r) for r in support):
                stale_entries.append((eid, level, sorted({str(r['code_ref']) for r in support})))
        elif level == 'reviewed' and not any(str(x).startswith('reviews/') for x in e.get('reviewed_by', [])):
            err(f'{eid}: verified=reviewed needs a reviewed_by reference to a reviews/ file')
        if st.get('populated') == 'corpus':
            impl = e.get('implementation', {})
            ev = e.get('corpus_evidence') or []
            edge_kind = eid[5:] if e.get('kind') == 'edge' and impl.get('registry') == 'model.EDGE_TYPES' else None
            if not impl.get('table') and not edge_kind:
                err(f'{eid}: populated=corpus is only checkable for table-backed entries and model.EDGE_TYPES edges '
                    '(snapshots persist tables, not views, columns or view-derived edges)')
            if not ev:
                err(f'{eid}: populated=corpus needs corpus_evidence (snapshot_id, table or edge_kind, count, observer); '
                    'unknown evidence is not success')
            for item in ev:
                target = ('edge_kind', edge_kind) if edge_kind else ('table', impl.get('table'))
                if not SNAPSHOT_ID.fullmatch(str(item.get('snapshot_id', ''))) or item.get(target[0]) != target[1] \
                        or not isinstance(item.get('count'), int) or item['count'] <= 0 or not item.get('observer'):
                    err(f'{eid}: corpus_evidence item {item} needs snapshot_id snapshot:<32 hex>, {target[0]} '
                        f'{target[1]!r}, a positive integer count and an observer')
        for ref in e.get('evidence', []):
            path, _, name = ref.partition('::')
            if not (root / path).exists():
                err(f'{eid}: evidence file missing {path}')
            elif name and not re.search(rf'def {re.escape(name)}\b', (root / path).read_text()):
                err(f'{eid}: evidence test missing {ref}')
        impl = e.get('implementation', {})
        for ref in e.get('sources', []) + impl.get('files', []):
            if not ref_path(root, ref).exists():
                err(f'{eid}: referenced file missing {ref}')
        for sym in impl.get('symbols', []):
            path, _, name = sym.partition('::')
            if name not in code['symbols'].get(path, set()):
                err(f'{eid}: symbol not found in code {sym}')
        ext = impl.get('external')
        if ext:
            repo = (real_root / ext.get('repo', '')).resolve()
            if not (repo / '.git').exists():
                warnings.append(f"{eid}: external repo {ext.get('repo')} not present; commit {ext.get('commit')} not read back")
            elif subprocess.run(['git', '-C', str(repo), 'cat-file', '-e', f"{ext.get('commit')}^{{commit}}"],
                                capture_output=True).returncode:
                err(f"{eid}: external commit {ext.get('commit')} not found in {ext.get('repo')}")
        for q in e.get('queue', []):
            if q not in queue['blocks']:
                err(f'{eid}: queue task {q} not in {QUEUE}')
        for d in e.get('decisions', []):
            if d not in by_id:
                err(f'{eid}: unknown decision {d}')
        if 'edge' in e:
            for ref in endpoints(e['edge'].get('source')) + endpoints(e['edge'].get('target')):
                if by_id.get(ref, {}).get('kind') != 'node':
                    err(f'{eid}: edge endpoint {ref} is not a node entry')
        if st.get('implemented') == 'none' and (impl.get('table') or impl.get('view')):
            err(f'{eid}: implemented=none but references a table/view')

    if baseline_stale:
        err(f'baseline stale: the checked code differs from baseline_commit {baseline} in {len(baseline_stale)} file(s) '
            f'under {"/".join(CODE_PATHS)} (e.g. {baseline_stale[:4]}); the atlas describes {baseline} only. Re-run the '
            'checks at the new code, record the runs and move baseline_commit')
    if stale_entries:
        err(f'{len(stale_entries)} entr(ies) with verified unit/disk rest only on runs whose code differs from the checked '
            f'code, e.g. {[f"{i} ({lv}, runs at {refs})" for i, lv, refs in stale_entries[:5]]}; re-run the suite at this '
            'code and record the run, or lower the status')

    # -- tables and fields
    owners = {}
    for e in entries:
        t = e.get('implementation', {}).get('table')
        if t:
            owners.setdefault(t, []).append(e)
    for t, cols in code['tables'].items():
        own = owners.get(t, [])
        if len(own) != 1:
            err(f'table {t}: expected exactly one atlas entry, found {len(own)}')
            continue
        e = own[0]
        # Static write detection is a heuristic (literal INSERT / Builder.add / Spool). A literal write
        # contradicting 'schema' is an error; a missing one is deferred to --runtime row counts.
        if t in code['written_tables'] and e['status']['implemented'] != 'code':
            err(f"{e['id']}: code writes table {t} but atlas says implemented={e['status']['implemented']}")
        elif t not in code['written_tables'] and e['status']['implemented'] == 'code':
            warnings.append(f"{e['id']}: no literal write to {t} found statically; confirm with --runtime")
        fields = {f['name']: f for f in e.get('fields', [])}
        for name in set(cols) - set(fields):
            err(f"{e['id']}: column {t}.{name} exists in code but not in atlas")
        for name in set(fields) - set(cols):
            err(f"{e['id']}: atlas field {name} not in code table {t}")
        for name in set(cols) & set(fields):
            c, f = cols[name], fields[name]
            if f.get('type') != c['type'] or f.get('nullable') != c['nullable'] or (f.get('key') == 'PK') != c['pk']:
                err(f"{e['id']}: field {name} atlas type/nullable/key {f.get('type')}/{f.get('nullable')}/"
                    f"{f.get('key')} != code {c['type']}/{c['nullable']}/{'PK' if c['pk'] else None}")
    for t, own in owners.items():
        if t not in code['tables']:
            err(f"{own[0]['id']}: atlas table {t} not found in code")

    # -- views
    atlas_views = {e['implementation'].get('view'): e for e in entries if e.get('implementation', {}).get('view')}
    for v in code['views'] - set(atlas_views):
        err(f'view {v}: exists in schema.sql but has no atlas entry')
    for v, e in atlas_views.items():
        if v not in code['views']:
            err(f"{e['id']}: view {v} not found in schema.sql")
        elif e['status']['implemented'] != 'code':
            err(f"{e['id']}: views are implemented=code")

    # -- node kinds
    atlas_nodes = {e['id'][5:]: e for e in entries if e.get('kind') == 'node'}
    for kind in code['node_kinds']:
        e = atlas_nodes.get(kind)
        if e is None:
            err(f'NodeKind {kind}: no atlas entry node:{kind}')
        elif e['status']['implemented'] == 'none':
            err(f'node:{kind}: in model.NodeKind but atlas says implemented=none')
        elif code['node_tables'].get(kind) != e['implementation'].get('table'):
            err(f"node:{kind}: nodes view table {code['node_tables'].get(kind)} != atlas {e['implementation'].get('table')}")
    if set(code['node_tables']) != code['node_kinds']:
        err(f"nodes view kinds {sorted(code['node_tables'])} != model.NodeKind {sorted(code['node_kinds'])}")
    for kind, e in atlas_nodes.items():
        if e['status']['implemented'] != 'none' and kind not in code['node_kinds']:
            err(f'node:{kind}: atlas says implemented but not in model.NodeKind')

    # -- edges
    for p in code['edge_problems']:
        err(f'EDGE_TYPES: unsupported static analysis, so the edge inventory cannot be proven complete: {p}')
    table_kind = {t: k for k, t in code['node_tables'].items()}
    for kind, (src, dst) in code['edge_types'].items():
        e = by_id.get('edge:' + kind)
        if e is None:
            err(f'EDGE_TYPES {kind}: no atlas entry edge:{kind}')
            continue
        if e['implementation'].get('registry') != 'model.EDGE_TYPES':
            err(f'edge:{kind}: registry must be model.EDGE_TYPES')
        if e['edge'].get('source') != 'node:' + src or e['edge'].get('target') != 'node:' + dst:
            err(f"edge:{kind}: atlas endpoints {e['edge'].get('source')}->{e['edge'].get('target')} != code {src}->{dst}")
        if kind in code['written_edges'] and e['status']['implemented'] != 'code':
            err(f"edge:{kind}: code writes this edge but atlas says implemented={e['status']['implemented']}")
        elif kind not in code['written_edges'] and e['status']['implemented'] == 'code':
            warnings.append(f'edge:{kind}: no literal .edge() write found statically; confirm with --runtime')
        if kind in code['written_edges'] and set(e['edge'].get('qualification', [])) != code['written_edges'][kind]:
            err(f"edge:{kind}: qualification {sorted(e['edge'].get('qualification', []))} != code "
                f"{sorted(code['written_edges'][kind])}")
    for kind in set(code['written_edges']) - set(code['edge_types']):
        err(f'code writes edge kind {kind} that is not registered in EDGE_TYPES')
    for kind, tables in code['portable'].items():
        e = by_id.get('edge:' + kind)
        if e is None:
            err(f'portable_edge {kind}: no atlas entry edge:{kind}')
            continue
        if e['implementation'].get('registry') != 'portable_edge' or e['status']['implemented'] != 'code':
            err(f'edge:{kind}: must be registry portable_edge with implemented=code')
        sources = {'node:' + table_kind.get(t, '?' + t) for t in tables}
        if set(endpoints(e['edge'].get('source'))) != sources:
            err(f"edge:{kind}: atlas sources {sorted(endpoints(e['edge'].get('source')))} != view {sorted(sources)}")
    for e in entries:
        if e.get('kind') != 'edge':
            continue
        kind, reg = e['id'][5:], e['implementation'].get('registry')
        if reg == 'model.EDGE_TYPES' and kind not in code['edge_types']:
            err(f"{e['id']}: claims model.EDGE_TYPES but code has no such kind")
        if reg == 'portable_edge' and kind not in code['portable']:
            err(f"{e['id']}: claims portable_edge but the view has no such kind")
        if reg == 'planned':
            if kind in code['edge_types'] or kind in code['portable']:
                err(f"{e['id']}: atlas says planned but code now defines it; update status")
            if e['status']['implemented'] != 'none':
                err(f"{e['id']}: planned edges must be implemented=none")
        if reg not in {'model.EDGE_TYPES', 'portable_edge', 'planned'}:
            err(f"{e['id']}: unknown registry {reg}")

    # -- manifest keys: every construction path, ** spreads resolved through call sites
    manifest_entries = [e for e in entries if e.get('implementation', {}).get('manifest_keys_of')]
    if len(manifest_entries) != 1:
        err(f'expected exactly one entry with implementation.manifest_keys_of, found {len(manifest_entries)}')
    for e in manifest_entries:
        complete = gate(e, 'manifest_keys', code['manifest_problems'], root, errors, warnings)
        paths = code['manifests']
        fields = {f['name']: f for f in e.get('fields', [])}
        written = set().union(*(set(p['keys']) for p in paths)) if paths else set()
        missing = written - set(fields)
        if missing:
            err(f"{e['id']}: manifest keys drift: code writes {sorted(missing)}, which the atlas does not list")
        if complete and paths:
            always = set.intersection(*({k for k, v in p['keys'].items() if not v[2]} for p in paths))
            extra = set(fields) - written
            if extra:
                err(f"{e['id']}: manifest keys drift: atlas lists {sorted(extra)}, which no construction path writes")
            for k in sorted(written & set(fields)):
                optional = fields[k].get('presence') == 'optional'
                srcs = set().union(*(p['sources'] for p in paths if k in p['keys']))
                if k in always and optional:
                    err(f"{e['id']}: manifest key {k} is written on every path but the atlas marks it optional")
                if k not in always and not optional:
                    err(f"{e['id']}: manifest key {k} is written only for sources {sorted(srcs)}; mark it presence=optional")
                if optional and fields[k].get('sources') is not None and set(fields[k]['sources']) != srcs:
                    err(f"{e['id']}: manifest key {k} atlas sources {sorted(fields[k]['sources'])} != code {sorted(srcs)}")
            for k in sorted(code['verify_required'] or ()):
                lacking = sorted({s for p in paths if k not in p['keys'] or p['keys'][k][2] for s in p['sources']})
                if lacking:
                    err(f"code: storage.verify() requires manifest key {k}, but paths for sources {lacking} may omit it")
                if fields.get(k, {}).get('presence') == 'optional':
                    err(f"{e['id']}: manifest key {k} is required by storage.verify() but the atlas marks it optional")

    # -- rights registry and source kinds
    ledgers = [e for e in entries if 'rights_keys' in e.get('implementation', {})]
    if len(ledgers) != 1:
        err(f'expected exactly one entry with implementation.rights_keys, found {len(ledgers)}')
    for e in ledgers:
        impl = e['implementation']
        gate(e, 'rights_keys', code['rights_problems'] + code['source_problems'], root, errors, warnings)
        reg = code['rights_keys']
        if set(impl['rights_keys']) != reg:
            err(f"{e['id']}: rights namespaces {sorted(impl['rights_keys'])} != code {sorted(reg)}")
        if e.get('values') is not None and set(e['values']) != set(impl['rights_keys']):
            err(f"{e['id']}: values describe {sorted(e['values'])} but rights_keys are {sorted(impl['rights_keys'])}")
        labels = set().union(*(p['sources'] for p in code['manifests'])) if code['manifests'] else set()
        discovered = (code['source_kinds'] | labels) - {'*', '?'}
        declared = impl.get('rights_sources') or {}
        status_of = impl.get('rights_status') or {}
        # Per-snapshot rights statements (anything that is not a direct RIGHTS[...] lookup), by source label.
        statements = {}
        for p in code['manifests']:
            if p['rights'][0] not in ('registry', 'missing'):
                for s in p['sources'] - {'*', '?'}:
                    statements.setdefault(s, set()).add(p['rights_statement'])
        for s in sorted(discovered - reg - set(declared)):
            err(f"{e['id']}: source kind {s} has no RIGHTS entry and no declared per-snapshot rights source "
                f"(implementation.rights_sources); rights must never be implicit")
        for s in sorted(set(statements) - set(declared)):
            err(f"{e['id']}: manifest paths for {s} write rights that are not a RIGHTS[...] lookup; declare the statement "
                f"under implementation.rights_sources.{s} with its statement_sha256 (a registry key does not cover it)")
        for s, d in sorted(declared.items()):
            if s in reg and s not in statements:
                err(f"{e['id']}: rights_sources declares {s}, but every path for it uses the RIGHTS registry")
            if s not in discovered | reg:
                err(f"{e['id']}: rights_sources declares {s}, which the code no longer uses")
            if not isinstance(d, dict) or not d.get('note'):
                err(f"{e['id']}: rights_sources.{s} must be an object with a note and statement_sha256")
            elif s in statements and d.get('statement_sha256') != statement_sha(statements[s]):
                err(f"{e['id']}: rights_sources.{s} statement changed in code (statement_sha256 "
                    f"{d.get('statement_sha256')} != code {statement_sha(statements[s])}); review the "
                    'rights text and record the new hash. Never invent or widen a grant')
        for s in sorted((reg | set(declared)) - set(status_of)):
            err(f"{e['id']}: implementation.rights_status has no expected status for {s}")
        for s, st in sorted(code['rights_status_code'].items()):
            if st is not None and status_of.get(s) is not None and status_of[s] != st:
                err(f"{e['id']}: RIGHTS[{s!r}] status is {st!r} in code but the atlas declares {status_of[s]!r}")
        for p in code['manifests']:
            origin, key = p['rights']
            if origin == 'missing':
                err(f"code: manifest path {p['where']} (sources {sorted(p['sources'])}) writes no rights")
            elif origin == 'registry' and key != '<source>' and key not in reg:
                err(f"code: manifest path {p['where']} looks up RIGHTS[{key!r}], which is not registered")
            elif origin.startswith('per-snapshot (registry') and key not in reg:
                err(f"code: manifest path {p['where']} falls back to RIGHTS[{key!r}], which is not registered")
            elif origin == 'registry' and key == '<source>':
                for s in sorted(p['sources'] - {'*', '?'} - reg):
                    err(f"code: manifest path {p['where']} looks up RIGHTS[source] for {s}, which is not registered")
            if p['sources'] & {'*', '?'} and not (origin == 'registry' and key == '<source>' and p['rights_indexed_by_source']):
                err(f"code: manifest path {p['where']} has a computed or caller-supplied source kind, so its rights must be "
                    f"exactly RIGHTS[source] (fails closed on unknown kinds); found {origin}")

    # -- runtime coverage of adapters/source kinds
    kinds = (code['source_kinds'] | code['rights_keys'] |
             (set().union(*(p['sources'] for p in code['manifests'])) if code['manifests'] else set())) - {'*', '?'}
    unexercised = atlas.get('runtime_unexercised') or {}
    for k in sorted(kinds - RUNTIME_DRIVEN - set(unexercised)):
        err(f'runtime: source kind {k} has no --runtime input and no runtime_unexercised reason; '
            f'its population claims cannot be checked')
    for k in sorted(set(unexercised) & RUNTIME_DRIVEN):
        err(f'runtime: {k} is listed in runtime_unexercised but the checker drives it')
    for k in sorted(set(unexercised) - kinds):
        err(f'runtime: runtime_unexercised lists {k}, which the code no longer uses')

    # -- queue
    for qid, blocks in queue['blocks'].items():
        if len(blocks) > 1:
            err(f'{QUEUE}: duplicate task heading {qid}')
        block = blocks[0]
        if block['status'] not in QUEUE_STATUSES:
            err(f"{QUEUE} {qid}: status {block['status']!r} not in {QUEUE_STATUSES}")
        if queue['rows'].get(qid) != block['status']:
            err(f"{QUEUE} {qid}: summary table status {queue['rows'].get(qid)!r} != block status {block['status']!r}")
        if block['depends'] is None:
            err(f'{QUEUE} {qid}: missing **Depends on:** line')
        for dep in block['depends'] or []:
            if dep not in queue['blocks']:
                err(f'{QUEUE} {qid}: depends on unknown {dep}')
        if block['status'] == 'DONE':
            tokens = [x.strip('`') for x in SHA_TOKEN.findall(block['body'])]
            commits = [c for c in (git.commit(x) for x in tokens) if c and git.is_ancestor(c, head)]
            if not commits:
                err(f'{QUEUE} {qid}: DONE without a backticked commit SHA in the block that resolves to a commit in the '
                    f'checked history ({head}); task IDs, trees and unknown hex do not count (tokens: {tokens[:6]})')
    for qid in set(queue['rows']) - set(queue['blocks']):
        err(f'{QUEUE}: summary row {qid} has no task block')
    for mid in sorted(set(MODEL_ID.findall(queue['text']))):
        if mid not in by_id:
            err(f'{QUEUE}: references unknown model ID {mid}')

    # -- pending live-tree sync record (informational; the contract above is the baseline)
    pending = atlas.get('pending_sync')
    if pending and worktree:
        now, then = fingerprint(root), pending.get('input_fingerprint') or {}
        changed = sorted(k for k in set(now) | set(then) if now.get(k) != then.get(k))
        if changed:
            warnings.append(f"pending_sync fingerprint ({pending.get('observed_at')}) no longer matches the live tree: "
                            f"{len(changed)} file(s) differ, e.g. {changed[:4]}; the drift list there is historical")

    # -- generated outputs
    clean = json.loads((root / ATLAS).read_text())
    md_text = (root / MD).read_text() if (root / MD).exists() else ''
    if MD_BEGIN not in md_text or MD_END not in md_text:
        err(f'{MD}: generated markers missing')
    elif md_text.split(MD_BEGIN, 1)[1].split(MD_END, 1)[0] != '\n' + render_md(clean) + '\n':
        err(f'{MD}: generated block is stale; run scripts/check_model_atlas.py --write')
    html_text = (root / HTML).read_text() if (root / HTML).exists() else ''
    block = HTML_BLOCK.search(html_text)
    if not block:
        err(f'{HTML}: atlas-data block missing')
    elif block.group(2) != html_data(clean):
        err(f'{HTML}: embedded atlas data is stale; run scripts/check_model_atlas.py --write')

    if runtime:
        runtime_check(root, atlas, entries, errors, warnings, samples, data_root, kinds, unexercised)
    return errors, warnings


