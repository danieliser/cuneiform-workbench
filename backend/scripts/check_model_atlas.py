def html_data(atlas: dict) -> str:
    return json.dumps(atlas, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/')


def write(root: Path) -> None:
    atlas = json.loads((root / ATLAS).read_text())
    md_path = root / MD
    md_text = md_path.read_text()
    if MD_BEGIN not in md_text or MD_END not in md_text:
        raise SystemExit(f'{MD}: add the generated markers first')
    head, rest = md_text.split(MD_BEGIN, 1)
    tail = rest.split(MD_END, 1)[1]
    md_path.write_text(head + MD_BEGIN + '\n' + render_md(atlas) + '\n' + MD_END + tail)
    html_path = root / HTML
    html_text = html_path.read_text()
    if not HTML_BLOCK.search(html_text):
        raise SystemExit(f'{HTML}: atlas-data block missing')
    data = html_data(atlas)
    html_path.write_text(HTML_BLOCK.sub(lambda m: m.group(1) + data + m.group(3), html_text, count=1))


