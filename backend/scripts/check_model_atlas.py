class Git:
    """Commit resolution for baseline, verification runs and DONE tasks. No repository = every lookup fails closed."""

    def __init__(self, repo: Path | None):
        self.repo = repo if repo is not None and (repo / '.git').exists() else None
        self._commit, self._tree = {}, {}

    def run(self, *args) -> subprocess.CompletedProcess:
        return subprocess.run(['git', '-C', str(self.repo), *args], capture_output=True, text=True)

    def commit(self, token) -> str | None:
        """Full SHA for a 7-40 hex token naming a commit; None for task IDs, trees, blobs, ambiguous or unknown hex."""
        token = str(token or '')
        if self.repo is None or not HEX_REF.fullmatch(token):
            return None
        if token not in self._commit:
            r = self.run('rev-parse', '--verify', '--quiet', f'{token}^{{commit}}')
            self._commit[token] = r.stdout.strip() if r.returncode == 0 else None
        return self._commit[token]

    def is_ancestor(self, sha: str, head: str) -> bool:
        return self.repo is not None and self.run('merge-base', '--is-ancestor', sha, head).returncode == 0

    def code_tree(self, sha: str) -> dict[str, str]:
        """{path: blob sha1} for CODE_PATHS at a commit."""
        if sha not in self._tree:
            r = self.run('ls-tree', '-r', '-z', sha, '--', *CODE_PATHS)
            out = {}
            for rec in r.stdout.split('\0'):
                if rec:
                    meta, path = rec.split('\t', 1)
                    mode, typ, blob = meta.split()
                    if typ == 'blob':
                        out[path] = blob
            self._tree[sha] = out
        return self._tree[sha]


def code_blobs(root: Path) -> dict[str, str]:
    """{path: git blob sha1} for CODE_PATHS in a directory (live tree or export), ignoring bytecode caches."""
    out = {}
    for top in CODE_PATHS:
        for p in sorted((root / top).rglob('*')):
            if p.is_file() and not p.is_symlink() and '__pycache__' not in p.parts and p.suffix != '.pyc' and p.name != '.DS_Store':
                data = p.read_bytes()
                out[str(p.relative_to(root))] = hashlib.sha1(b'blob %d\0' % len(data) + data).hexdigest()
    return out


def tree_diff(a: dict, b: dict) -> list[str]:
    return sorted(k for k in set(a) | set(b) if a.get(k) != b.get(k))


# ---------------------------------------------------------------- static analysis

class Unsupported(Exception):
    """A code form the analyzer cannot resolve. Always reported as an error (or a declared contract)."""

    def __init__(self, file: str, node, msg: str):
        self.file = file
        super().__init__(f"{file}:{getattr(node, 'lineno', '?')}: {msg}")


def const_str(node) -> str | None:
    return node.value if isinstance(node, ast.Constant) and isinstance(node.value, str) else None


def pos(node) -> tuple[int, int]:
    return (node.lineno, node.col_offset)


class At:
    """A bare source position for error messages."""

    def __init__(self, line: int):
        self.lineno = line


def names_in(target) -> set[str]:
    return {n.id for n in ast.walk(target) if isinstance(n, ast.Name)}


class Package:
    """Parsed cuneiform/*.py with parent links, so expressions can be resolved across call sites."""

    def __init__(self, root: Path):
        self.root = root
        self.modules: dict[str, ast.Module] = {}
        self.parent: dict[int, ast.AST] = {}
        self.module_of: dict[int, str] = {}
        for p in sorted((root / 'cuneiform').glob('*.py')):
            rel = str(p.relative_to(root))
            tree = ast.parse(p.read_text(), rel)
            self.modules[rel] = tree
            for n in ast.walk(tree):
                self.module_of[id(n)] = rel
                for c in ast.iter_child_nodes(n):
                    self.parent[id(c)] = n

    def scope_of(self, node):
        p = self.parent.get(id(node))
        while p is not None and not isinstance(p, (ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda, ast.Module)):
            p = self.parent.get(id(p))
        return p

    def module_rel(self, imp: ast.ImportFrom, name: str | None = None) -> str | None:
        """Resolve `from .x import y` / `from cuneiform.x import y` to cuneiform/x.py."""
        mod = imp.module or ''
        if imp.level == 1:
            target = mod if mod else name
        elif imp.level == 0 and mod.startswith('cuneiform.'):
            target = mod.split('.', 1)[1]
        elif imp.level == 0 and mod == 'cuneiform':
            target = name
        else:
            return None
        rel = f'cuneiform/{target}.py' if target else None
        return rel if rel in self.modules else None

    def aliases(self, rel: str, defining: str, name: str) -> tuple[set[str], set[str]]:
        """Names in module `rel` bound to `defining`.`name`, and names bound to the module itself."""
        direct = {name} if rel == defining else set()
        modalias = set()
        for n in ast.walk(self.modules[rel]):
            if isinstance(n, ast.ImportFrom):
                for a in n.names:
                    if self.module_rel(n) == defining and a.name == name:
                        direct.add(a.asname or a.name)
                    if n.module in (None, 'cuneiform') and self.module_rel(n, a.name) == defining:
                        modalias.add(a.asname or a.name)
            elif isinstance(n, ast.Import):
                for a in n.names:
                    if a.name == 'cuneiform.' + Path(defining).stem:
                        if a.asname:
                            modalias.add(a.asname)
        return direct, modalias


def scope_statements(scope):
    """Yield (statement, conditional) for statements of one scope; nested def bodies are not entered."""
    def walk(body, cond):
        for s in body:
            yield s, cond
            if isinstance(s, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                continue
            if isinstance(s, (ast.If, ast.For, ast.AsyncFor, ast.While)):
                yield from walk(s.body, True)
                yield from walk(s.orelse, True)
            elif isinstance(s, (ast.With, ast.AsyncWith)):
                yield from walk(s.body, cond)
            elif isinstance(s, ast.Try) or type(s).__name__ == 'TryStar':
                yield from walk(s.body, cond)
                for h in s.handlers:
                    yield from walk(h.body, True)
                yield from walk(s.orelse, cond)
                yield from walk(s.finalbody, cond)
            elif isinstance(s, ast.Match):
                for c in s.cases:
                    yield from walk(c.body, True)
    yield from walk(scope.body, False)


def find_binding(pkg: Package, rel: str, scope, name: str, upos):
    """Return ('value', expr, frame, bpos) | ('param', func) for `name` as seen at position upos."""
    if isinstance(scope, ast.Lambda):
        raise Unsupported(rel, scope, f'`{name}` used inside a lambda')
    is_func = isinstance(scope, (ast.FunctionDef, ast.AsyncFunctionDef))
    cands = []
    for s, cond in scope_statements(scope):
        spos = pos(s)
        # Only statements that finish before the use; `meta = dict(meta, ...)` must not resolve to itself.
        if is_func and (s.end_lineno, s.end_col_offset) > upos:
            continue
        if isinstance(s, ast.Assign):
            for t in s.targets:
                if isinstance(t, ast.Name) and t.id == name:
                    cands.append((spos, s.value, cond))
                elif isinstance(t, (ast.Tuple, ast.List)) and name in names_in(t):
                    v = s.value
                    if (isinstance(v, (ast.Tuple, ast.List)) and len(v.elts) == len(t.elts)
                            and not any(isinstance(x, ast.Starred) for x in t.elts + v.elts)):
                        for tx, vx in zip(t.elts, v.elts):
                            if isinstance(tx, ast.Name) and tx.id == name:
                                cands.append((spos, vx, cond))
                    else:
                        raise Unsupported(rel, s, f'`{name}` bound by unpacking a non-literal value')
        elif isinstance(s, ast.AnnAssign) and isinstance(s.target, ast.Name) and s.target.id == name and s.value:
            cands.append((spos, s.value, cond))
        elif isinstance(s, (ast.For, ast.AsyncFor)) and name in names_in(s.target):
            raise Unsupported(rel, s, f'`{name}` bound by a loop')
        elif isinstance(s, (ast.With, ast.AsyncWith)) and any(i.optional_vars is not None and name in names_in(i.optional_vars) for i in s.items):
            raise Unsupported(rel, s, f'`{name}` bound by a with-statement')
        elif isinstance(s, ast.ImportFrom) and any((a.asname or a.name) == name for a in s.names):
            if is_func:
                raise Unsupported(rel, s, f'`{name}` bound by a local import')
            a = next(a for a in s.names if (a.asname or a.name) == name)
            target = pkg.module_rel(s)
            if target is None:
                raise Unsupported(rel, s, f'`{name}` imported from outside the package')
            cands.append((spos, ('import', target, a.name), cond))
    for n in ast.walk(scope):
        if isinstance(n, ast.NamedExpr) and n.target.id == name and pkg.scope_of(n) is scope:
            raise Unsupported(rel, n, f'`{name}` bound by an assignment expression')
    if cands:
        spos, value, cond = max(cands, key=lambda c: c[0])
        if cond:
            raise Unsupported(rel, At(spos[0]), f'`{name}` is bound conditionally; the key set depends on control flow')
        if isinstance(value, tuple):
            _, target, orig = value
            return find_binding(pkg, target, pkg.modules[target], orig, END)
        return ('value', value, (rel, scope, spos), spos)
    if is_func:
        a = scope.args
        params = {x.arg for x in a.posonlyargs + a.args + a.kwonlyargs}
        if name in params:
            return ('param', scope)
        return find_binding(pkg, rel, pkg.modules[rel], name, END)
    raise Unsupported(rel, At(upos[0]) if upos != END else None, f'cannot resolve name `{name}`')


def call_site_args(pkg: Package, rel: str, func, param: str):
    """Yield (argument expression, frame) for `param` at every call of top-level function `func`."""
    if pkg.scope_of(func) is not pkg.modules[rel]:
        raise Unsupported(rel, func, f'`{func.name}` is nested or a method; its call sites are not resolved')
    sites = []
    for mrel, tree in pkg.modules.items():
        direct, modalias = pkg.aliases(mrel, rel, func.name)
        for n in ast.walk(tree):
            if isinstance(n, ast.Call):
                f = n.func
                if (isinstance(f, ast.Name) and f.id in direct) or (
                        isinstance(f, ast.Attribute) and f.attr == func.name and isinstance(f.value, ast.Name) and f.value.id in modalias):
                    sites.append((mrel, n))
            elif isinstance(n, ast.Name) and n.id in direct and isinstance(n.ctx, ast.Load):
                p = pkg.parent.get(id(n))
                if not (isinstance(p, ast.Call) and p.func is n):
                    raise Unsupported(mrel, n, f'`{func.name}` is referenced without being called; its arguments cannot be traced')
    if not sites:
        raise Unsupported(rel, func, f'`{param}` is a parameter of `{func.name}`, which has no call sites in the package')
    a = func.args
    positional = [x.arg for x in a.posonlyargs + a.args]
    for mrel, call in sites:
        frame = (mrel, pkg.scope_of(call), pos(call))
        if any(isinstance(x, ast.Starred) for x in call.args) or any(k.arg is None for k in call.keywords):
            raise Unsupported(mrel, call, f'call to `{func.name}` uses *args/**kwargs')
        kw = next((k.value for k in call.keywords if k.arg == param), None)
        if kw is not None:
            yield kw, frame
            continue
        if param in positional and positional.index(param) < len(call.args):
            yield call.args[positional.index(param)], frame
            continue
        default = None
        if param in positional:
            i = positional.index(param) - (len(positional) - len(a.defaults))
            default = a.defaults[i] if i >= 0 else None
        else:
            i = [x.arg for x in a.kwonlyargs].index(param)
            default = a.kw_defaults[i]
        if default is None:
            raise Unsupported(mrel, call, f'call to `{func.name}` omits `{param}`')
        yield default, (rel, pkg.modules[rel], pos(func))


def binds_locally(func, name: str) -> bool:
    """True when a nested function has its own parameter or assignment named `name` (so it does not capture ours)."""
    if isinstance(func, (ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda)):
        a = func.args
        if name in {x.arg for x in a.posonlyargs + a.args + a.kwonlyargs} | {x.arg for x in (a.vararg, a.kwarg) if x}:
            return True
    body = func.body if isinstance(func.body, list) else [func.body]
    for s in body:
        for n in ast.walk(s):
            if isinstance(n, ast.Name) and n.id == name and isinstance(n.ctx, ast.Store):
                return True
    return False


# Package functions known not to mutate their argument. Each is accepted only while its body keeps the stated shape.
PURE_PACKAGE = {('cuneiform/model.py', 'canonical'): 'a single `return json.dumps(<first parameter>, ...)`'}


def pure_package_call(pkg: Package, call: ast.Call) -> bool:
    rel = pkg.module_of.get(id(call))
    for (defining, fname) in PURE_PACKAGE:
        tree = pkg.modules.get(defining)
        func = next((s for s in (tree.body if tree else []) if isinstance(s, ast.FunctionDef) and s.name == fname), None)
        if func is None or rel is None:
            continue
        body = [s for s in func.body if not (isinstance(s, ast.Expr) and isinstance(s.value, ast.Constant))]
        first = (func.args.posonlyargs + func.args.args)[:1]
        shaped = (len(body) == 1 and isinstance(body[0], ast.Return) and isinstance(body[0].value, ast.Call)
                  and ast.unparse(body[0].value.func) == 'json.dumps' and first and body[0].value.args
                  and isinstance(body[0].value.args[0], ast.Name) and body[0].value.args[0].id == first[0].arg)
        direct, modalias = pkg.aliases(rel, defining, fname)
        f = call.func
        named = (isinstance(f, ast.Name) and f.id in direct) or (
            isinstance(f, ast.Attribute) and f.attr == fname and isinstance(f.value, ast.Name) and f.value.id in modalias)
        if named and shaped:
            return True
    return False


def read_only_use(pkg: Package, n: ast.Name) -> bool:
    """A load of a tracked dict that cannot change its key set (R2 escape analysis)."""
    p = pkg.parent.get(id(n))
    if isinstance(p, ast.Call) and any(a is n for a in p.args) and pure_package_call(pkg, p):
        return True                                   # canonical(name): serializes, never mutates
    if isinstance(p, ast.Subscript) and p.value is n:
        return True                                   # name[k] read, or name[k] = v (tracked separately)
    if isinstance(p, ast.Dict) and any(k is None and v is n for k, v in zip(p.keys, p.values)):
        return True                                   # {**name}: copies keys into a new dict
    if isinstance(p, ast.Compare) and any(c is n for c in p.comparators) and all(isinstance(o, (ast.In, ast.NotIn)) for o in p.ops):
        return True                                   # k in name
    if isinstance(p, ast.Call) and isinstance(p.func, ast.Name) and p.func.id in PURE_BUILTINS and any(a is n for a in p.args):
        return True                                   # dict(name, ...), len(name), sorted(name) ...
    if isinstance(p, ast.Attribute) and p.value is n and p.attr in READONLY_METHODS:
        g = pkg.parent.get(id(p))
        return isinstance(g, ast.Call) and g.func is p
    return False


def apply_mutations(pkg: Package, rel: str, scope, name: str, bpos, upos, paths: list[dict]) -> list[dict]:
    """Add constant subscript keys written to `name` between its binding and the use; fail on other mutations
    and on any load that lets the dict escape (alias, call argument, unknown method, closure capture)."""
    conds = {id(s): c for s, c in scope_statements(scope)}
    for n in ast.walk(scope):
        own = pkg.scope_of(n) is scope
        npos = pos(n) if hasattr(n, 'lineno') else None
        in_range = own and npos is not None and bpos < npos < upos
        if isinstance(n, ast.Name) and n.id == name and isinstance(n.ctx, ast.Load):
            if not own:
                inner = pkg.scope_of(n)
                if not binds_locally(inner, name) and not read_only_use(pkg, n):
                    raise Unsupported(rel, n, f'`{name}` is captured by a nested function that lets it escape, which could '
                                              'change its keys')
            elif in_range and not read_only_use(pkg, n):
                p = pkg.parent.get(id(n))
                raise Unsupported(rel, n, f'`{name}` escapes before its keys are read (used in '
                                          f'`{ast.unparse(p)[:60] if p is not None else name}`); aliases, helper calls and '
                                          'unknown methods could add keys the analyzer cannot follow')
        if isinstance(n, ast.Call) and isinstance(n.func, ast.Attribute) and isinstance(n.func.value, ast.Name) \
                and n.func.value.id == name and n.func.attr in MUTATORS and (in_range or not own):
            raise Unsupported(rel, n, f'`{name}.{n.func.attr}(...)` changes the key set in a way the analyzer cannot follow')
        if isinstance(n, ast.AugAssign) and name in names_in(n.target) and (in_range or not own):
            raise Unsupported(rel, n, f'augmented assignment to `{name}`')
        if isinstance(n, ast.Delete) and any(name in names_in(t) for t in n.targets) and (in_range or not own):
            raise Unsupported(rel, n, f'`del` on `{name}`')
        if isinstance(n, ast.Assign):
            for t in n.targets:
                if isinstance(t, ast.Subscript) and isinstance(t.value, ast.Name) and t.value.id == name:
                    if not own:
                        raise Unsupported(rel, n, f'`{name}[...]` assigned inside a nested function')
                    if not in_range:
                        continue
                    key = const_str(t.slice)
                    if key is None:
                        raise Unsupported(rel, n, f'`{name}[<non-constant>]` assignment')
                    for p in paths:
                        p[key] = (n.value, (rel, scope, pos(n)), conds.get(id(n), True))
    return paths


def dict_paths(pkg: Package, expr, frame, depth: int = 0) -> list[dict]:
    """Every possible key set of a dict expression: list of {key: (value expr, frame, optional)}."""
    rel = frame[0]
    if depth > 16:
        raise Unsupported(rel, expr, 'dict resolution too deep')
    if isinstance(expr, ast.Dict):
        paths = [{}]
        for k, v in zip(expr.keys, expr.values):
            if k is None:
                subs = dict_paths(pkg, v, frame, depth + 1)
                paths = [{**p, **q} for p in paths for q in subs]
            elif const_str(k) is not None:
                for p in paths:
                    p[k.value] = (v, frame, False)
            else:
                raise Unsupported(rel, k, 'non-constant dict key')
        return paths
    if isinstance(expr, ast.Call) and isinstance(expr.func, ast.Name) and expr.func.id == 'dict':
        paths = [{}]
        for a in expr.args:
            if isinstance(a, ast.Starred):
                raise Unsupported(rel, a, 'dict(*args)')
            subs = dict_paths(pkg, a, frame, depth + 1)
            paths = [{**p, **q} for p in paths for q in subs]
        for kw in expr.keywords:
            if kw.arg is None:
                subs = dict_paths(pkg, kw.value, frame, depth + 1)
                paths = [{**p, **q} for p in paths for q in subs]
            else:
                for p in paths:
                    p[kw.arg] = (kw.value, frame, False)
        return paths
    if isinstance(expr, ast.Name):
        return name_paths(pkg, expr.id, frame, pos(expr), depth + 1)
    raise Unsupported(rel, expr, f'cannot resolve the keys of `{ast.unparse(expr)[:70]}`')


def name_paths(pkg: Package, name: str, frame, upos, depth: int) -> list[dict]:
    rel, scope, _ = frame
    found = find_binding(pkg, rel, scope, name, upos)
    if found[0] == 'value':
        _, value, bframe, bpos = found
        paths = [dict(p) for p in dict_paths(pkg, value, bframe, depth)]
        if bframe[1] is scope:
            paths = apply_mutations(pkg, rel, scope, name, bpos, upos, paths)
        return paths
    func = found[1]
    out = []
    for arg, cframe in call_site_args(pkg, rel, func, name):
        out += [dict(p) for p in dict_paths(pkg, arg, cframe, depth)]
    return apply_mutations(pkg, rel, scope, name, pos(func), upos, out)


def str_values(pkg: Package, expr, frame, depth: int = 0) -> set[str]:
    """Constant strings an expression can take; '*' when it is supplied by a caller at run time."""
    if depth > 8:
        return {'*'}
    if const_str(expr) is not None:
        return {expr.value}
    if isinstance(expr, ast.Name):
        try:
            found = find_binding(pkg, frame[0], frame[1], expr.id, pos(expr))
        except Unsupported:
            return {'*'}
        if found[0] == 'value':
            return str_values(pkg, found[1], found[2], depth + 1)
        try:
            out = set()
            for arg, cframe in call_site_args(pkg, frame[0], found[1], expr.id):
                out |= str_values(pkg, arg, cframe, depth + 1)
            return out
        except Unsupported:
            return {'*'}
    return {'*'}


def name_stores(pkg: Package, scope, name: str) -> int:
    """How many times `name` is bound, rebound or deleted in `scope` (nested `global`/`nonlocal` count as rebinding)."""
    count = 0
    for n in ast.walk(scope):
        if isinstance(n, (ast.Global, ast.Nonlocal)) and name in n.names:
            count += 2
        elif pkg.scope_of(n) is not scope:
            continue
        elif isinstance(n, ast.Name) and n.id == name and isinstance(n.ctx, (ast.Store, ast.Del)):
            count += 1
        elif isinstance(n, (ast.Import, ast.ImportFrom)):
            count += sum((a.asname or a.name).split('.')[0] == name for a in n.names)
        elif isinstance(n, ast.ExceptHandler) and n.name == name:
            count += 1
    return count


def digest_origin(pkg: Package, expr, frame, depth: int = 0) -> str:
    """Where a manifest_sha256 value comes from: 'copy' when it is read from another record (attribute, subscript or
    `.get(...)`), 'computed' when it is produced here (digest call, constant, ...). A name is resolved through its
    lexical binding: a local bound once to a computed value is computed, and a parameter takes the origin of every
    call-site argument. A rebound, conditionally bound or unresolvable name raises Unsupported; it is never assumed
    to be a copy."""
    rel, scope = frame[0], frame[1]
    if depth > 8:
        raise Unsupported(rel, expr, 'manifest_sha256 value resolution too deep')
    if isinstance(expr, (ast.Attribute, ast.Subscript)):
        return 'copy'
    if isinstance(expr, ast.Call) and isinstance(expr.func, ast.Attribute) and expr.func.attr == 'get':
        return 'copy'
    if not isinstance(expr, ast.Name):
        return 'computed'
    name = expr.id
    found = find_binding(pkg, rel, scope, name, pos(expr))
    if found[0] == 'param':
        func = found[1]
        if name_stores(pkg, func, name):
            raise Unsupported(rel, expr, f'parameter `{name}` is rebound in `{func.name}`; its manifest_sha256 origin is unknown')
        origins = {digest_origin(pkg, arg, cframe, depth + 1) for arg, cframe in call_site_args(pkg, rel, func, name)}
        return 'computed' if 'computed' in origins else 'copy'
    _, value, bframe, _ = found
    if name_stores(pkg, bframe[1], name) > 1:
        raise Unsupported(bframe[0], expr, f'`{name}` is bound more than once; its manifest_sha256 origin is unknown')
    return digest_origin(pkg, value, bframe, depth + 1)


SIGN_KEY = 'manifest_sha256'


def mutator_writes(call: ast.Call) -> tuple[ast.AST | None, list] | None:
    """For `x.update(...)`, `x.setdefault(k, v)`, `x.__setitem__(k, v)` and `[operator.]setitem(x, k, v)`: the receiver
    and the (key, value) pairs it writes, a key of None standing for a merged dict expression. None for other calls."""
    f, args = call.func, list(call.args)
    if isinstance(f, ast.Attribute) and f.attr in ('update', 'setdefault', '__setitem__'):
        recv = f.value
        if isinstance(recv, ast.Name) and recv.id == 'dict':          # dict.update(x, ...): unbound method form
            if not args:
                return None
            recv = args.pop(0)
        if f.attr == 'update':
            return recv, [(None, a) for a in args] + [(k.arg, k.value) for k in call.keywords]
        if args:
            return recv, [(const_str(args[0]), args[1] if len(args) > 1 else ast.Constant(None))]
        return None
    if ((isinstance(f, ast.Name) and f.id == 'setitem') or (isinstance(f, ast.Attribute) and f.attr == 'setitem')) and len(call.args) == 3:
        return call.args[0], [(const_str(call.args[1]), call.args[2])]
    return None


def signs(pkg: Package, value, frame) -> bool:
    return digest_origin(pkg, value, frame) == 'computed'


def dict_signs(pkg: Package, n, frame) -> bool:
    """A dict literal or dict(...) call that writes a computed manifest_sha256."""
    if isinstance(n, ast.Dict):
        return any(const_str(k) == SIGN_KEY and signs(pkg, v, frame) for k, v in zip(n.keys, n.values))
    if isinstance(n, ast.Call) and isinstance(n.func, ast.Name) and n.func.id == 'dict':
        return any(k.arg == SIGN_KEY and signs(pkg, k.value, frame) for k in n.keywords)
    return False


def written_after(pkg: Package, rel: str, scope, name: str, after) -> Unsupported | None:
    """A key-changing write to `name` after it was signed (N2). Such keys would not be compared with the atlas."""
    for n in ast.walk(scope):
        if pkg.scope_of(n) is not scope or not hasattr(n, 'lineno') or pos(n) <= after:
            continue
        key = None
        if isinstance(n, (ast.Assign, ast.AugAssign, ast.AnnAssign, ast.Delete)):
            targets = n.targets if isinstance(n, (ast.Assign, ast.Delete)) else [n.target]
            hit = [t for t in targets if isinstance(t, ast.Subscript) and isinstance(t.value, ast.Name) and t.value.id == name]
            if isinstance(n, ast.AugAssign) and isinstance(n.target, ast.Name) and n.target.id == name:
                hit = [n.target]
            if not hit:
                continue
            key = const_str(hit[0].slice) if isinstance(hit[0], ast.Subscript) else '|='
        elif isinstance(n, ast.Call):
            w = mutator_writes(n)
            f = n.func
            if w and isinstance(w[0], ast.Name) and w[0].id == name:
                key = ','.join(k if k is not None else '<merged dict>' for k, _ in w[1])
            elif isinstance(f, ast.Attribute) and isinstance(f.value, ast.Name) and f.value.id == name and f.attr in MUTATORS:
                key = f.attr
            else:
                continue
        else:
            continue
        if key == SIGN_KEY:
            continue
        return Unsupported(rel, n, f"`{name}` gets key `{key}` after it is signed (line {after[0]}); keys written after "
                                   'signing are not compared with the atlas. Add them before the signing line')
    return None


def snapshot_manifests(pkg: Package) -> tuple[list[dict], list[Unsupported]]:
    """Find every signing site in the package and keep those whose key set carries snapshot_id.

    A signing site is any write of a computed `manifest_sha256` value (see digest_origin): `x['manifest_sha256'] = v`,
    `x.update(manifest_sha256=v)` / `x.update({...})`, `x.setdefault('manifest_sha256', v)`, `[operator.]setitem`,
    a dict literal `{..., 'manifest_sha256': v}` or `dict(..., manifest_sha256=v)`, plus `manifest = {...}`.
    Records that only copy a digest (ledger rows, receipts, bindings) are not signing sites. A site whose keys or
    digest origin cannot be resolved is a problem (fail closed), whatever its variable is called."""
    sites, early = {}, []
    for rel, tree in pkg.modules.items():
        for n in ast.walk(tree):
            scope = pkg.scope_of(n)
            frame = (rel, scope, pos(n) if hasattr(n, 'lineno') else END)
            try:
                if isinstance(n, (ast.Dict, ast.Call)) and dict_signs(pkg, n, frame):
                    parent = pkg.parent.get(id(n))
                    if isinstance(parent, (ast.BinOp, ast.AugAssign)):
                        raise Unsupported(rel, n, 'a signed dict merged with an operator (`|`, `|=`, ...); build it as '
                                                  "`{**body, 'manifest_sha256': ...}` instead")
                    if isinstance(parent, ast.keyword):
                        parent = pkg.parent.get(id(parent))
                    if isinstance(parent, ast.Call) and mutator_writes(parent):
                        continue                      # merged into a receiver; that call is the site
                    sites[(rel, id(n))] = (rel, scope, n, pos(n), None)
                    if isinstance(parent, ast.Assign) and len(parent.targets) == 1 and isinstance(parent.targets[0], ast.Name):
                        late = written_after(pkg, rel, scope, parent.targets[0].id, (parent.end_lineno, parent.end_col_offset))
                        if late:
                            early.append(late)
                    continue
                if isinstance(n, ast.Call) and (w := mutator_writes(n)):
                    recv, pairs = w
                    signed = any(k == SIGN_KEY and signs(pkg, v, frame) for k, v in pairs) or any(
                        k is None and dict_signs(pkg, v, frame) for k, v in pairs)
                    if not signed:
                        continue
                    if not isinstance(recv, ast.Name):
                        raise Unsupported(rel, n, f'signed record `{ast.unparse(recv)[:40]}` is not a plain name')
                    sites[(rel, id(scope), recv.id, pos(n))] = (rel, scope, recv.id, pos(n), n)
                    late = written_after(pkg, rel, scope, recv.id, (n.end_lineno, n.end_col_offset))
                    if late:
                        early.append(late)
                    continue
                if not isinstance(n, ast.Assign):
                    continue
                for t in n.targets:
                    if isinstance(t, ast.Subscript) and const_str(t.slice) == SIGN_KEY and signs(pkg, n.value, frame):
                        if not isinstance(t.value, ast.Name):
                            raise Unsupported(rel, n, f'signed record `{ast.unparse(t.value)[:40]}` is not a plain name')
                        sites[(rel, id(scope), t.value.id)] = (rel, scope, t.value.id, (n.lineno, n.col_offset + 1), None)
                        late = written_after(pkg, rel, scope, t.value.id, (n.end_lineno, n.end_col_offset))
                        if late:
                            early.append(late)
                    if isinstance(t, ast.Name) and t.id == 'manifest' and (isinstance(n.value, ast.Dict) or (
                            isinstance(n.value, ast.Call) and isinstance(n.value.func, ast.Name) and n.value.func.id == 'dict')):
                        sites.setdefault((rel, id(scope), 'manifest'), (rel, scope, 'manifest', END, None))
            except Unsupported as exc:
                early.append(exc)
    results, problems = [], early
    for rel, scope, var, upos, call in sites.values():
        where = f"{rel}::{getattr(scope, 'name', '<module>')}"
        try:
            if isinstance(var, str):
                paths = name_paths(pkg, var, (rel, scope, upos), upos, 0)
            else:
                paths = [dict(p) for p in dict_paths(pkg, var, (rel, scope, upos))]
            if call is not None:
                frame = (rel, scope, upos)
                added = [{}]
                for k, v in mutator_writes(call)[1]:
                    if k is None:
                        added = [{**a, **q} for a in added for q in dict_paths(pkg, v, frame)]
                    else:
                        for a in added:
                            a[k] = (v, frame, False)
                paths = [{**p, **a} for p in paths for a in added]
        except Unsupported as exc:
            problems.append(exc)
            continue
        has = ['snapshot_id' in p for p in paths]
        if any(has) and not all(has):
            problems.append(Unsupported(rel, scope, f'{where}: some construction paths carry snapshot_id and some do not'))
        elif all(has) and paths:
            for p in paths:
                src = p.get('source')
                labels = str_values(pkg, src[0], src[1]) if src else {'?'}
                results.append({'where': where, 'keys': p, 'sources': labels})
    if not results and not problems:
        problems.append(Unsupported('cuneiform', None, 'no snapshot-manifest construction (signed dict with snapshot_id) found'))
    return results, problems


def verify_required(pkg: Package) -> tuple[set[str] | None, list[Unsupported]]:
    tree = pkg.modules.get('cuneiform/storage.py')
    func = next((n for n in (tree.body if tree else []) if isinstance(n, ast.FunctionDef) and n.name == 'verify'), None)
    if func is None:
        return None, [Unsupported('cuneiform/storage.py', None, 'storage.verify() not found; required manifest keys unknown')]
    for s, _ in scope_statements(func):
        if isinstance(s, ast.Assign) and any(isinstance(t, ast.Name) and t.id == 'required' for t in s.targets) \
                and isinstance(s.value, ast.Set) and all(const_str(e) is not None for e in s.value.elts):
            return {e.value for e in s.value.elts}, []
    return None, [Unsupported('cuneiform/storage.py', func, 'verify() has no literal `required = {...}` key set')]


def registry(pkg: Package, defining: str, name: str) -> tuple[dict, list[Unsupported]]:
    """Keys of a module-level registry dict plus every `NAME[<const>] = ...` anywhere in the package."""
    out, problems = {}, []
    tree = pkg.modules.get(defining)
    if tree is None:
        return out, [Unsupported(defining, None, 'module missing')]
    binds = [s for s in tree.body if isinstance(s, ast.Assign) and any(isinstance(t, ast.Name) and t.id == name for t in s.targets)]
    if len(binds) != 1 or not isinstance(binds[0].value, ast.Dict):
        return out, [Unsupported(defining, binds[0] if binds else None, f'{name} must be bound exactly once to a dict literal')]
    for k, v in zip(binds[0].value.keys, binds[0].value.values):
        if const_str(k) is None:
            problems.append(Unsupported(defining, v, f'{name} literal has a non-constant key or ** spread'))
        else:
            out[k.value] = v
    for rel, mtree in pkg.modules.items():
        direct, modalias = pkg.aliases(rel, defining, name)

        def is_ref(x):
            return (isinstance(x, ast.Name) and x.id in direct) or (
                isinstance(x, ast.Attribute) and x.attr == name and isinstance(x.value, ast.Name) and x.value.id in modalias)
        for n in ast.walk(mtree):
            if is_ref(n) and isinstance(getattr(n, 'ctx', None), ast.Load) and not read_only_use(pkg, n) and not (
                    isinstance(pkg.parent.get(id(n)), ast.Attribute) and pkg.parent[id(n)].attr in MUTATORS):
                p = pkg.parent.get(id(n))
                problems.append(Unsupported(rel, n, f'{name} escapes (used in `{ast.unparse(p)[:60] if p is not None else name}`); '
                                                    'an alias or helper could add namespaces the analyzer cannot see'))
            if isinstance(n, ast.Assign):
                for t in n.targets:
                    if isinstance(t, ast.Subscript) and is_ref(t.value):
                        if const_str(t.slice) is None:
                            problems.append(Unsupported(rel, n, f'{name}[<non-constant>] assignment'))
                        else:
                            out[t.slice.value] = n.value
                    elif is_ref(t) and n is not binds[0]:
                        problems.append(Unsupported(rel, n, f'{name} rebound'))
            elif isinstance(n, ast.AugAssign) and (is_ref(n.target) or (isinstance(n.target, ast.Subscript) and is_ref(n.target.value))):
                problems.append(Unsupported(rel, n, f'augmented assignment to {name}'))
            elif isinstance(n, ast.Call) and isinstance(n.func, ast.Attribute) and n.func.attr in MUTATORS and is_ref(n.func.value):
                problems.append(Unsupported(rel, n, f'{name}.{n.func.attr}(...) mutates the registry'))
            elif isinstance(n, ast.Delete) and any(isinstance(t, ast.Subscript) and is_ref(t.value) for t in n.targets):
                problems.append(Unsupported(rel, n, f'del {name}[...]'))
    return out, problems


def source_kinds(pkg: Package) -> tuple[set[str], list[Unsupported]]:
    """Source kinds the code dispatches on: `source == 'x'`, `x['source'] == 'x'`, `... in {...}`/NAME."""
    kinds, problems = set(), []

    def is_source(x):
        return (isinstance(x, ast.Name) and x.id == 'source') or (
            isinstance(x, ast.Subscript) and const_str(x.slice) == 'source')
    for rel, tree in pkg.modules.items():
        for n in ast.walk(tree):
            if not isinstance(n, ast.Compare) or len(n.ops) != 1:
                continue
            left, op, right = n.left, n.ops[0], n.comparators[0]
            if not is_source(left):
                if is_source(right) and isinstance(op, (ast.Eq, ast.NotEq)) and const_str(left) is not None:
                    kinds.add(left.value)
                continue
            if isinstance(op, (ast.Eq, ast.NotEq)):
                if const_str(right) is not None:
                    kinds.add(right.value)
            elif isinstance(op, (ast.In, ast.NotIn)):
                container = right
                if isinstance(right, ast.Name):
                    try:
                        found = find_binding(pkg, rel, pkg.modules[rel], right.id, END)
                        container = found[1] if found[0] == 'value' else None
                    except Unsupported as exc:
                        problems.append(exc)
                        continue
                if isinstance(container, ast.Call) and isinstance(container.func, ast.Name) and container.func.id in ('set', 'frozenset') and container.args:
                    container = container.args[0]
                if isinstance(container, (ast.Set, ast.Tuple, ast.List)) and all(const_str(e) is not None for e in container.elts):
                    kinds.update(e.value for e in container.elts)
                else:
                    problems.append(Unsupported(rel, n, f'source compared against `{ast.unparse(right)[:50]}`, which is not a literal set'))
    return kinds, problems


def rights_origin(pkg: Package, value, frame, depth: int = 0) -> tuple[str, str | None]:
    """('registry', key) for adapters.RIGHTS[...] lookups; ('per-snapshot', None) otherwise."""
    direct, modalias = pkg.aliases(frame[0], 'cuneiform/adapters.py', 'RIGHTS')

    def registry_key(x):
        if isinstance(x, ast.Subscript) and (
                (isinstance(x.value, ast.Name) and x.value.id in direct) or
                (isinstance(x.value, ast.Attribute) and x.value.attr == 'RIGHTS' and isinstance(x.value.value, ast.Name) and x.value.value.id in modalias)):
            return const_str(x.slice) or '<source>'
        return None
    key = registry_key(value)
    if key:
        return 'registry', key
    if isinstance(value, ast.BoolOp) and isinstance(value.op, ast.Or) and registry_key(value.values[-1]):
        return 'per-snapshot (registry fallback)', registry_key(value.values[-1])
    if isinstance(value, ast.Name) and depth < 4:
        try:
            found = find_binding(pkg, frame[0], frame[1], value.id, pos(value))
            if found[0] == 'value':
                return rights_origin(pkg, found[1], found[2], depth + 1)
        except Unsupported:
            pass
    return 'per-snapshot', None


def registry_index(value):
    """The index expression of a direct `RIGHTS[<expr>]` lookup (None for anything else)."""
    return value.slice if isinstance(value, ast.Subscript) else None


def rights_statement(pkg: Package, expr, frame, depth: int = 0) -> str:
    """Stable fingerprint text of a rights expression and every same-package binding it reads (R4.4).
    Line moves do not change it; any change to the expression or the literals it resolves to does."""
    parts = [ast.dump(expr)]
    if depth > 4:
        return parts[0]
    for n in ast.walk(expr):
        if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Load):
            try:
                found = find_binding(pkg, frame[0], frame[1], n.id, pos(n))
            except Unsupported:
                parts.append(f'unresolved:{n.id}')
                continue
            parts.append(rights_statement(pkg, found[1], found[2], depth + 1) if found[0] == 'value' else f'param:{n.id}')
        elif isinstance(n, ast.Attribute) and isinstance(n.value, ast.Name):
            for target in pkg.modules:
                if n.value.id in pkg.aliases(frame[0], target, n.attr)[1]:
                    try:
                        found = find_binding(pkg, target, pkg.modules[target], n.attr, END)
                        parts.append(rights_statement(pkg, found[1], found[2], depth + 1))
                    except Unsupported:
                        parts.append(f'unresolved:{n.value.id}.{n.attr}')
    return '\n'.join(parts)


def statement_sha(texts) -> str:
    return hashlib.sha256('\n--\n'.join(sorted(texts)).encode()).hexdigest()


