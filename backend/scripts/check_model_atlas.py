def cell(value) -> str:
    if value is None or value == '' or value == []:
        return '—'
    if isinstance(value, list):
        value = ', '.join(str(v) for v in value)
    return str(value).replace('|', '\\|').replace('\n', ' ')


def backing(e: dict) -> str:
    impl = e.get('implementation', {})
    for key in ('table', 'view', 'table_column'):
        if impl.get(key):
            return f'{key} `{impl[key]}`'
    if impl.get('registry') and impl['registry'] != 'planned':
        return impl['registry']
    if impl.get('symbols'):
        return ', '.join(f'`{s}`' for s in impl['symbols'])
    if impl.get('external'):
        return f"external `{impl['external'].get('repo')}`@`{impl['external'].get('commit')}`"
    return '—'


