def run_analyzer_case(files: dict, expect) -> tuple[bool, str]:
    with tempfile.TemporaryDirectory(prefix='atlas-analyzer-') as tmp:
        pkgdir = Path(tmp) / 'cuneiform'
        pkgdir.mkdir()
        for name, src in files.items():
            (pkgdir / f'{name}.py').write_text(src)
        pkg = Package(Path(tmp))
        paths, problems = snapshot_manifests(pkg)
        rights, rproblems = registry(pkg, 'cuneiform/adapters.py', 'RIGHTS')
        kinds, kproblems = source_kinds(pkg)
        if expect == 'unsupported':
            return bool(problems), f'problems={[str(p) for p in problems]}'
        if isinstance(expect, tuple):                 # ('unsupported', text): the specific refusal is reported
            return any(expect[1] in str(p) for p in problems), f'problems={[str(p) for p in problems]}'
        if expect == 'rights-unsupported':
            return bool(rproblems), f'rights problems={[str(p) for p in rproblems]}'
        if problems:
            return False, f'unexpected problems {[str(p) for p in problems]}'
        keys = set().union(*(set(p['keys']) for p in paths)) if paths else set()
        always = set.intersection(*(set(p['keys']) for p in paths)) if paths else set()
        srcs = {k: set().union(*(p['sources'] for p in paths if k in p['keys'])) for k in keys}
        ok = expect(keys, keys - always, srcs, set(rights), kinds)
        return bool(ok), f'keys={sorted(keys)} optional={sorted(keys - always)} rights={sorted(rights)} kinds={sorted(kinds)}'


def self_test(root: Path, ref: str, repo: Path | None = None) -> int:
    def runs_at(atlas, code_ref):
        for r in atlas.get('verification_runs', []):
            r['code_ref'] = code_ref

    def first_disk(atlas):
        """A verified=disk entry; synthesized from a code entry plus a disk run at the baseline when none exists (R8)."""
        e = next((x for x in atlas['entries'] if x['status']['verified'] == 'disk'), None)
        if e is not None:
            return e
        run = next((r for r in atlas.get('verification_runs', []) if r.get('level') == 'disk' and r.get('outcome') == 'pass'
                    and r.get('code_ref') == atlas.get('baseline_commit')), None)
        if run is None:
            run = {'id': 'selftest-disk', 'level': 'disk', 'outcome': 'pass', 'observer': 'self-test', 'read_back': False,
                   'date': 'self-test', 'code_ref': atlas.get('baseline_commit'), 'command': 'self-test', 'result': 'synthetic',
                   'attribution': 'synthetic run added by --self-test'}
            atlas.setdefault('verification_runs', []).append(run)
        e = next(x for x in atlas['entries'] if x['status']['implemented'] == 'code'
                 and any(str(r).startswith('tests/') for r in x.get('evidence', [])))
        e['status']['verified'] = 'disk'
        e['verified_by'] = [run['id']]
        return e

    def cite_unaccepted(atlas):
        snaps = atlas.setdefault('corpus_snapshots', {})
        sid = next((k for k, v in snaps.items() if v.get('status') != 'accepted'), None)
        if sid is None:
            sid = 'snapshot:' + '0' * 32
            snaps[sid] = {'status': 'pending-review', 'manifest_sha256': '0' * 64, 'note': 'self-test'}
        e = next((x for x in atlas['entries'] if x.get('corpus_evidence')), None)
        if e is None:
            e = first_code_table(atlas)
            e['status']['populated'] = 'corpus'
            e['corpus_evidence'] = []
        target = ('edge_kind', e['id'][5:]) if e.get('kind') == 'edge' else ('table', e['implementation'].get('table'))
        e['corpus_evidence'].append({'snapshot_id': sid, target[0]: target[1], 'count': 1, 'observer': 'self-test'})

    def accepted_without_review(atlas):
        snaps = atlas.setdefault('corpus_snapshots', {})
        sid = next((k for k, v in snaps.items() if v.get('status') == 'accepted'), None)
        if sid is None:
            sid = 'snapshot:' + '1' * 32
            snaps[sid] = {'status': 'accepted', 'manifest_sha256': '1' * 64, 'note': 'self-test'}
        snaps[sid]['accepted_by'] = []

    def first_code_table(atlas):
        return next(e for e in atlas['entries'] if e.get('implementation', {}).get('table') and e['status']['implemented'] == 'code')

    def set_corpus(atlas):
        e = first_code_table(atlas)
        e['status']['populated'] = 'corpus'
        e.pop('corpus_evidence', None)

    cases = [
        ('new column in schema.sql', edit_text('cuneiform/schema.sql',
            lambda t, r: re.sub(r'(CREATE TABLE \w+\()', r'\1selftest_col VARCHAR,', t, count=1)), 'selftest_col'),
        ('new edge type in EDGE_TYPES literal', edit_text('cuneiform/model.py',
            lambda t, r: re.sub(r'(EDGE_TYPES\s*=\s*\{)', "\\1'SELFTEST_LIT': ('Artifact', 'Artifact'), ", t, count=1)), 'SELFTEST_LIT'),
        ('new edge type by EDGE_TYPES[...] assignment', append('cuneiform/model.py',
            "EDGE_TYPES['SELFTEST_SUB'] = ('Artifact', 'Artifact')"), 'SELFTEST_SUB'),
        ('parser version bump', edit_text('cuneiform/model.py',
            lambda t, r: re.sub(r"(PARSER_VERSION\s*=\s*')([^']*)'", r"\1\2-selftest'", t, count=1)), 'versions'),
        ('populated claim on a schema-only table (target chosen at run time)',
         mutate_schema_table(lambda e: e['status'].update(populated='sample')), 'requires implemented=code'),
        ('undeclared write into a schema-only table (target chosen at run time)', undeclared_write, 'code writes table'),
        ('stale HTML data block', edit_text(HTML, lambda t, r: t.replace('"atlas_revision":', '"atlas_revision_tampered":', 1)), 'stale'),
        ('stale markdown block', edit_text(MD, lambda t, r: t.replace('### Status counts by domain', '### Status counts (edited by hand)', 1)), 'stale'),
        ('new constant manifest key', edit_text('cuneiform/storage.py',
            lambda t, r: manifest_dict_insert(t, r, "'selftest_key':1,")), "'selftest_key'"),
        ('manifest key hidden behind a ** spread', edit_text('cuneiform/storage.py',
            lambda t, r: manifest_dict_insert(t, r, "**{'selftest_spread':1},")), "'selftest_spread'"),
        ('unresolvable ** spread fails instead of passing', edit_text('cuneiform/storage.py',
            lambda t, r: manifest_dict_insert(t, r, "**_selftest_helper(),")), 'unsupported static analysis (manifest_keys)'),
        ('atlas field removed although code writes it', edit_atlas(lambda a: next(
            e for e in a['entries'] if e.get('implementation', {}).get('manifest_keys_of'))['fields'].pop()), 'manifest keys drift'),
        ('new rights namespace by RIGHTS[...] assignment', append('cuneiform/adapters.py',
            "RIGHTS['selftest-src'] = RIGHTS[next(iter(RIGHTS))]"), 'selftest-src'),
        ('RIGHTS.update(...) fails instead of passing', append('cuneiform/adapters.py',
            "RIGHTS.update({'selftest-upd': {}})"), 'unsupported static analysis (rights_keys)'),
        ('source kind without rights', append('cuneiform/storage.py',
            "def _selftest_source(manifest):\n    return manifest['source'] == 'selftest-kind'"), 'source kind selftest-kind has no RIGHTS entry'),
        ('populated=corpus without receipt evidence', edit_atlas(set_corpus), 'populated=corpus needs corpus_evidence'),
        ('verified=disk without a named run', edit_atlas(lambda a: first_disk(a).pop('verified_by', None)), 'must name its run'),
        ('verification runs at a commit that does not exist', edit_atlas(lambda a: runs_at(a, '0000000')), 'rest only on runs'),
        ('verification run code_ref is not a commit (one hex character)', edit_atlas(
            lambda a: a['verification_runs'][0].__setitem__('code_ref', str(a['verification_runs'][0]['code_ref'])[:1])), 'does not resolve'),
        ('baseline_commit is not a commit', edit_atlas(lambda a: a.__setitem__('baseline_commit', 'deadbee')), 'does not resolve'),
        ('contract-neutral code edit makes the baseline stale', append('cuneiform/model.py', '# selftest: contract-neutral edit'),
         'baseline stale'),
        ('corpus evidence cites a non-accepted snapshot', edit_atlas(cite_unaccepted), 'never independent evidence'),
        ('accepted corpus snapshot without a review reference', edit_atlas(accepted_without_review), 'accepted needs accepted_by'),
        ('DONE citing only a task ID', edit_text(QUEUE, lambda t, r: _done_without_sha(t, '(task `8d17b311`)')), 'DONE without'),
        ('unknown queue reference', edit_atlas(lambda a: a['entries'][0].__setitem__('queue', ['Q-999'])), 'Q-999'),
        ('queue status drift', edit_text(QUEUE, lambda t, r: re.sub(
            r'^(- \*\*Status:\*\*\s*`)(\w+)`', lambda m: m.group(1) + ('BLOCKED' if m.group(2) != 'BLOCKED' else 'TODO') + '`',
            t, count=1, flags=re.M)), 'summary table status'),
        ('DONE without a commit SHA', edit_text(QUEUE, lambda t, r: _done_without_sha(t)), 'DONE without'),
        ('always-written manifest key marked optional', edit_atlas(lambda a: next(
            f for e in a['entries'] if e.get('implementation', {}).get('manifest_keys_of')
            for f in e['fields'] if f['name'] == 'snapshot_id').update(presence='optional')), 'marks it optional'),
        ('corpus claim on a view is refused', edit_atlas(lambda a: next(
            e for e in a['entries'] if e.get('implementation', {}).get('view'))['status'].update(populated='corpus')),
         'only checkable for table-backed entries'),
    ]
    failures = 0
    with tempfile.TemporaryDirectory(prefix='atlas-selftest-') as tmp:
        def fresh():
            copy = Path(tmp) / 'repo'
            if copy.exists():
                shutil.rmtree(copy)
            if ref == 'WORKTREE':
                shutil.copytree(root, copy, ignore=shutil.ignore_patterns('.git', '__pycache__', '.output', '*.pyc'))
            else:
                copy.mkdir()
                materialize(root, ref, copy)
            return copy
        base_errors, _ = check(fresh(), real_root=root, repo=repo)
        if ref == 'WORKTREE':
            print(f'BASE  live tree copy has {len(base_errors)} pre-existing error(s); cases count only new ones')
        else:
            ok = not base_errors
            failures += not ok
            print(f"{'PASS' if ok else 'FAIL'}  baseline copy at {ref} passes" + ('' if ok else f'  -> {base_errors[:3]}'))
        baseline = set(base_errors)
        for name, apply, expect in cases:
            copy = fresh()
            try:
                apply(copy)
                errors, _ = check(copy, real_root=root, repo=repo)
                new = [x for x in errors if x not in baseline]
                ok = any(expect in x for x in new)
                detail = '' if ok else f'  -> new errors: {new[:3]}'
            except Exception as exc:  # a crashing case is a FAIL, never a pass
                ok, detail = False, f'  -> {type(exc).__name__}: {exc}'
            failures += not ok
            print(f"{'PASS' if ok else 'FAIL'}  {name}{detail}")
        for name, files, expect in analyzer_cases():
            try:
                ok, detail = run_analyzer_case(files, expect)
            except Exception as exc:
                ok, detail = False, f'{type(exc).__name__}: {exc}'
            failures += not ok
            print(f"{'PASS' if ok else 'FAIL'}  {name}" + ('' if ok else f'  -> {detail}'))
    total = len(cases) + len(analyzer_cases()) + (ref != 'WORKTREE')
    print(f'self-test ({ref}): {total - failures}/{total} cases behaved as expected; real files untouched')
    return 1 if failures else 0


def _done_without_sha(text: str, note: str = '') -> str:
    """Mark the first non-DONE task DONE in both the summary row and its block, without adding a commit SHA
    (`note` may add a backticked non-commit hex token such as a task ID)."""
    blocks = list(re.finditer(r'^## (Q-\d{3})\b.*$', text, re.M))
    for i, h in enumerate(blocks):
        body = text[h.end():blocks[i + 1].start() if i + 1 < len(blocks) else len(text)]
        st = re.search(r'^- \*\*Status:\*\*\s*`(\w+)`', body, re.M)
        if st and st.group(1) != 'DONE' and not SHA_TOKEN.search(body):
            qid = h.group(1)
            start = h.end() + st.start()
            text = text[:start] + body[st.start():st.end()].replace(st.group(1), 'DONE') + (f' {note}' if note else '') + text[h.end() + st.end():]
            return re.sub(rf'^(\|\s*{qid}\s*\|[^|]*\|\s*)`\w+`', r'\1`DONE`', text, count=1, flags=re.M)
    raise AssertionError('no task block without a SHA to mark DONE')


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parent.parent)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--check', action='store_true', help='validate only (default)')
    mode.add_argument('--write', action='store_true', help='regenerate MODEL-ATLAS.md block and HTML data, then check')
    mode.add_argument('--self-test', action='store_true',
                      help='inject mismatches into a temporary copy; uses committed code at --git-ref (default HEAD), '
                           'or the uncommitted tree with --git-ref WORKTREE')
    parser.add_argument('--runtime', action='store_true', help='also verify populated status in memory (needs duckdb)')
    parser.add_argument('--samples', type=Path, default=EVIDENCE_DIR, help='retained sample directory for --runtime')
    parser.add_argument('--data-root', type=Path, default=DATA_ROOT, help='read-only data root holding snapshots/ for corpus evidence')
    parser.add_argument('--git-ref', metavar='REV',
                        help='check committed code at REV (e.g. HEAD) with the working-tree atlas/queue files overlaid; '
                             'use while another worker has uncommitted code changes. --self-test defaults to HEAD.')
    parser.add_argument('--fingerprint', action='store_true', help='print the live input fingerprint as JSON and exit')
    parser.add_argument('--repo', type=Path, help='git repository used to resolve baseline, run and DONE commits '
                                                  '(default: --root; needed when --root is an export without .git)')
    args = parser.parse_args()
    root = args.root.resolve()
    if args.fingerprint:
        print(json.dumps(fingerprint(root), indent=1, sort_keys=True))
        return 0
    repo = args.repo.resolve() if args.repo else root
    if args.self_test:
        return self_test(root, args.git_ref or 'HEAD', repo)
    if args.write:
        write(root)
    if args.git_ref:
        with tempfile.TemporaryDirectory(prefix='atlas-ref-') as tmp:
            errors, warnings = check(materialize(root, args.git_ref, Path(tmp)), runtime=args.runtime, samples=args.samples,
                                     real_root=root, data_root=args.data_root, repo=repo)
            print(f'checked code at {args.git_ref} with working-tree atlas/queue overlaid')
    else:
        errors, warnings = check(root, runtime=args.runtime, samples=args.samples, data_root=args.data_root, worktree=True,
                                 repo=repo)
    for w in warnings:
        print('warning:', w)
    for e in errors:
        print('error:', e)
    print(f"model atlas: {'OK' if not errors else f'{len(errors)} error(s)'}"
          f"{' (runtime population checked)' if args.runtime else ''}")
    return 1 if errors else 0


if __name__ == '__main__':
    sys.exit(main())
