def materialize(root: Path, ref: str, dest: Path) -> Path:
    """Export committed code at `ref`, then overlay the working-tree atlas/queue files."""
    import io
    import tarfile
    data = subprocess.run(['git', '-C', str(root), 'archive', '--format=tar', ref],
                          check=True, capture_output=True).stdout
    with tarfile.open(fileobj=io.BytesIO(data)) as tar:
        tar.extractall(dest, filter='data')
    for rel in OWNED + tuple(str(p.relative_to(root)) for p in sorted((root / 'reviews').glob('*.md'))):
        if (root / rel).exists():  # review files are read-only references; overlaid so evidence links resolve
            (dest / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(root / rel, dest / rel)
    return dest


def edit_text(path: str, fn):
    def apply(r: Path):
        p = r / path
        text = p.read_text()
        new = fn(text, r)
        if new == text:
            raise AssertionError(f'self-test mutation did not change {path}')
        p.write_text(new)
    return apply


def append(path: str, code: str):
    return edit_text(path, lambda t, r: t.rstrip('\n') + '\n\n' + code.strip('\n') + '\n')


